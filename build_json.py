    # index majors by base name
    majors_by_base = {}
    for mj in school["majors"]:
        bn = base_name(mj)
        majors_by_base.setdefault(bn, []).append(mj["name"])

    sec_colleges = []
    assigned = set()
    # For id=21 (merged school), do not dedupe globally: same major name appears in
    # both pre-merger schools and should be listed under both colleges.
    dedupe = (oid != 21)
    for col_name, base_list in info["colleges"]:
        listed_set = []
        seen_in_col = set()
        for bn in base_list:
            if bn in majors_by_base:
                # list distinct names (a base name may have variants with parentheticals)
                for full_name in majors_by_base[bn]:
                    if full_name in seen_in_col:
                        continue
                    if dedupe and full_name in assigned:
                        continue
                    listed_set.append(full_name)
                    seen_in_col.add(full_name)
                    assigned.add(full_name)
        if listed_set:
            sec_colleges.append({"name": col_name, "majors": listed_set, "source": info["source"]})

    # unassigned -> 其他/公共教学部
    unassigned = []
    for mj in school["majors"]:
        if mj["name"] not in assigned:
            unassigned.append(mj["name"])
    if unassigned:
        sec_colleges.append({"name": "其他/公共教学部", "majors": unassigned, "source": info["source"]})

    region_out["colleges"].append({
        "id": oid,
        "name": school["name"],
        "website": school["website"],
        "secondaryColleges": sec_colleges,
        "note": info.get("note", "")
    })

