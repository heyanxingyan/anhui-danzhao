# Helper: build per-major data with map {major_name: (ret, rev, rural)}
def build_school(sid, name, mapping, has_breakdown=True, note=""):
    majors_out = []
    for m in baseline[str(sid)]['majors']:
        n = m['name']
        if n in mapping:
            r, rv, ru = mapping[n]
        else:
            r, rv, ru = 0, 0, 0
        majors_out.append({"name": n, "retiredMilitary": r, "revolutionaryArea": rv, "ruralDoctor": ru})
    return {"id": sid, "name": name, "hasPerMajorBreakdown": has_breakdown, "note": note, "majors": majors_out}

